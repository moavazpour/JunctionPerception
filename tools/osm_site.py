"""Derive site priors from OpenStreetMap around a camera position (run once at installation).

Outputs the bearing of the road the camera looks along, the junction ahead (stop-line reference point)
and pedestrian crossings, as a YAML snippet for the site config.

    python tools/osm_site.py --lat 48.175995 --lon 11.555590 --bearing 95 [--radius 450]
"""
from __future__ import annotations

import argparse
import json
import math
import urllib.parse
import urllib.request

OVERPASS = "https://overpass-api.de/api/interpreter"
R = 6378137.0


def enu(lat0, lon0, lat, lon):
    return (math.radians(lon - lon0) * R * math.cos(math.radians(lat0)), math.radians(lat - lat0) * R)


def geo(lat0, lon0, e, n):
    return (lat0 + math.degrees(n / R), lon0 + math.degrees(e / (R * math.cos(math.radians(lat0)))))


def bearing_of(dx, dy):
    return math.degrees(math.atan2(dx, dy)) % 360


def query(lat, lon, radius):
    q = f"""[out:json][timeout:25];
    (way(around:{radius},{lat},{lon})["highway"~"primary|secondary|tertiary|trunk|residential|unclassified"];
     node(around:{radius},{lat},{lon})["highway"="traffic_signals"];
     way(around:{radius},{lat},{lon})["footway"="crossing"];
     node(around:{radius},{lat},{lon})["highway"="crossing"];);
    out body; >; out skel qt;"""
    data = urllib.parse.urlencode({"data": q}).encode()
    req = urllib.request.Request(OVERPASS, data=data, headers={"User-Agent": "junction-perception-site-setup"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lat", type=float, required=True)
    ap.add_argument("--lon", type=float, required=True)
    ap.add_argument("--bearing", type=float, required=True, help="approximate viewing direction (deg)")
    ap.add_argument("--radius", type=float, default=450)
    args = ap.parse_args()
    d = query(args.lat, args.lon, args.radius)
    nodes = {}
    for e in d["elements"]:
        # Way members come back a second time without tags ("out skel"); keep the tagged copy.
        if e["type"] == "node" and ("tags" in e or e["id"] not in nodes):
            nodes[e["id"]] = e
    ways = [e for e in d["elements"] if e["type"] == "way"]
    fwd = (math.sin(math.radians(args.bearing)), math.cos(math.radians(args.bearing)))

    # Road bearing: road segments close to the viewing axis, 20-200 m ahead, roughly parallel to it.
    best = None
    for w in ways:
        if "highway" not in w.get("tags", {}) or w["tags"].get("footway") == "crossing":
            continue
        pts = [enu(args.lat, args.lon, nodes[i]["lat"], nodes[i]["lon"]) for i in w["nodes"] if i in nodes]
        for a, b in zip(pts, pts[1:]):
            mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
            ahead = mid[0] * fwd[0] + mid[1] * fwd[1]
            lateral = abs(mid[0] * fwd[1] - mid[1] * fwd[0])
            seg = (b[0] - a[0], b[1] - a[1])
            L = math.hypot(*seg)
            if L < 5 or not (20 < ahead < 220):
                continue
            par = abs(seg[0] * fwd[0] + seg[1] * fwd[1]) / L
            if par < 0.85:
                continue
            score = L * par / (1 + lateral / 20)
            if best is None or score > best[0]:
                br = bearing_of(*seg)
                if abs(((br - args.bearing + 180) % 360) - 180) > 90:
                    br = (br + 180) % 360
                best = (score, br, w["tags"].get("name", ""), w["tags"].get("lanes"))
    # Junction ahead: the nearest traffic signal (or crossing) roughly on the axis.
    signals = []
    for n in nodes.values():
        tags = n.get("tags", {})
        if tags.get("highway") != "traffic_signals":
            continue
        e, nn = enu(args.lat, args.lon, n["lat"], n["lon"])
        ahead = e * fwd[0] + nn * fwd[1]
        lateral = abs(e * fwd[1] - nn * fwd[0])
        if ahead > 10 and lateral < 40:
            signals.append((ahead, lateral, n))
    signals.sort(key=lambda s: s[0])
    crossings = []
    for w in ways:
        if w.get("tags", {}).get("footway") != "crossing":
            continue
        pts = [enu(args.lat, args.lon, nodes[i]["lat"], nodes[i]["lon"]) for i in w["nodes"] if i in nodes]
        if len(pts) < 2:
            continue
        a, b = pts[0], pts[-1]
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        if L < 2:
            continue
        ux, uy = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        nx, ny = -uy * 2.0, ux * 2.0  # 4 m wide zebra
        poly = [(a[0] + nx, a[1] + ny), (b[0] + nx, b[1] + ny), (b[0] - nx, b[1] - ny), (a[0] - nx, a[1] - ny)]
        mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
        if mid[0] * fwd[0] + mid[1] * fwd[1] > 0 and abs(mid[0] * fwd[1] - mid[1] * fwd[0]) < 60:
            crossings.append([geo(args.lat, args.lon, *p) for p in poly])

    print("# --- generated by tools/osm_site.py from OpenStreetMap ---")
    if best:
        print(f"# road: {best[2]!r}, lanes tag: {best[3]}")
        print(f"calibration:\n  road_bearing_deg: {best[1]:.1f}")
    if signals:
        ahead, lat_off, n = signals[0]
        print(f"# nearest traffic signal ahead: {ahead:.0f} m (lateral {lat_off:.0f} m)")
        print(f"map:\n  stop_line: {{lat: {n['lat']:.7f}, lon: {n['lon']:.7f}}}")
    if crossings:
        print("  crosswalks:")
        for poly in crossings[:8]:
            print("    - [" + ", ".join(f"[{la:.7f}, {lo:.7f}]" for la, lo in poly) + "]")


if __name__ == "__main__":
    main()
